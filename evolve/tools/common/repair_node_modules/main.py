"""repair_node_modules — delete node_modules (+ optional lock) then reinstall (Phase 35 M3b).

Explicit call only — not triggered by playbook heuristics.
"""

from __future__ import annotations

import os
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

_DEFAULT_TIMEOUT = 1800
_MAX_OUTPUT_CHARS = 64 * 1024
_LOCK_FILES = (
    "package-lock.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "npm-shrinkwrap.json",
)


def _agent_root() -> Path:
    current = Path(__file__).resolve().parent
    for directory in (current, *current.parents):
        evolve_marker = directory / "evolve"
        if (evolve_marker / "_index.core.toml").is_file() or (evolve_marker / "_index.toml").is_file():
            return directory
    raise RuntimeError("could not locate agent root")


def _load_paths():
    core = _agent_root() / "agent-core"
    if str(core) not in sys.path:
        sys.path.insert(0, str(core))
    from paths import AgentPaths, PathDeniedForWriteError, PathOutOfBoundsError

    return AgentPaths, PathDeniedForWriteError, PathOutOfBoundsError


def _truncate(text: str, limit: int = _MAX_OUTPUT_CHARS) -> tuple[str, bool]:
    if len(text) <= limit:
        return text, False
    return text[:limit] + "\n…(truncated)", True


def _timeout_sec(payload: dict[str, Any]) -> int:
    raw = payload.get("timeout_sec")
    env_default = os.environ.get("MY_AGENT_RUN_COMMAND_LONG_TIMEOUT_SEC", str(_DEFAULT_TIMEOUT))
    try:
        default = int(env_default)
    except ValueError:
        default = _DEFAULT_TIMEOUT
    default = max(600, default)
    if raw is None or raw == "":
        return default
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return default
    return max(1, min(value, default))


def _coalesce_working_dir(payload: dict[str, Any]) -> str:
    for key in ("working_dir", "cwd", "path"):
        value = payload.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def _resolve_cwd(paths, PathOutOfBoundsError, path_arg: str) -> Path:
    if not path_arg:
        raise ValueError("working_dir is required")
    text = path_arg.strip().replace("\\", "/").lstrip("/")
    try:
        return paths.resolve_under_agent(text, must_exist=True)
    except PathOutOfBoundsError:
        raise
    except (FileNotFoundError, TypeError, ValueError):
        if not text.startswith("workspace/"):
            return paths.resolve_under_agent(f"workspace/{text}", must_exist=True)
        raise


def _rmtree_robust(target: Path) -> None:
    """Delete a directory tree; on Windows chmod read-only files then retry."""

    def _onexc(func: Any, path: str, exc_info: Any) -> None:  # noqa: ARG001
        try:
            os.chmod(path, stat.S_IWRITE)
            func(path)
        except Exception:
            raise

    # Python 3.12+: onexc; older: onerror
    try:
        shutil.rmtree(target, onexc=_onexc)  # type: ignore[call-arg]
    except TypeError:
        shutil.rmtree(target, onerror=_onexc)  # type: ignore[call-arg]


def _find_npm() -> str:
    npm = shutil.which("npm")
    if npm:
        return npm
    for candidate in (
        r"C:\Program Files\nodejs\npm.cmd",
        r"C:\Program Files (x86)\nodejs\npm.cmd",
    ):
        if Path(candidate).is_file():
            return candidate
    return "npm"


def _resolve_pkg(cwd: Path, preferred: str | None) -> tuple[str, str, list[str]]:
    """Return (label, bin_path, install_argv)."""
    label = (preferred or "").strip().lower()
    if label in {"", "auto"}:
        try:
            core = _agent_root() / "agent-core"
            if str(core) not in sys.path:
                sys.path.insert(0, str(core))
            from project_env import load_env_near, resolve_package_manager_bin

            env = load_env_near(cwd)
            label, binary = resolve_package_manager_bin(env)
        except Exception:
            label, binary = "npm", _find_npm()
    elif label == "npm":
        binary = _find_npm()
    elif label == "pnpm":
        binary = shutil.which("pnpm") or "pnpm"
    elif label == "yarn":
        binary = shutil.which("yarn") or "yarn"
    else:
        raise ValueError("package_manager must be auto|npm|pnpm|yarn")

    if label == "yarn":
        argv = [binary, "install"]
    elif label == "pnpm":
        argv = [binary, "install"]
    else:
        label = "npm"
        argv = [binary, "install"]
    return label, binary, argv


def run_repair(payload: dict[str, Any]) -> dict[str, Any]:
    AgentPaths, PathDeniedForWriteError, PathOutOfBoundsError = _load_paths()
    paths = AgentPaths.discover(start=_agent_root())

    working_dir_arg = _coalesce_working_dir(payload)
    dry_run = bool(payload.get("dry_run", False))
    remove_lock = bool(payload.get("remove_lock", False))
    skip_install = bool(payload.get("skip_install", False))
    timeout_sec = _timeout_sec(payload)
    preferred = payload.get("package_manager")
    preferred_s = preferred.strip() if isinstance(preferred, str) else "auto"

    try:
        cwd = _resolve_cwd(paths, PathOutOfBoundsError, working_dir_arg)
    except PathOutOfBoundsError as exc:
        return {"ok": False, "error": f"working_dir out of bounds: {exc}"}
    except (PathDeniedForWriteError, ValueError, FileNotFoundError, TypeError) as exc:
        return {"ok": False, "error": str(exc)}

    cwd_rel = paths.to_agent_relative(cwd) or "."
    package_json = cwd / "package.json"
    node_modules = cwd / "node_modules"

    try:
        pm_label, pm_bin, install_argv = _resolve_pkg(cwd, preferred_s)
    except ValueError as exc:
        return {"ok": False, "error": str(exc), "cwd": cwd_rel}

    locks_present = [name for name in _LOCK_FILES if (cwd / name).is_file()]
    plan = {
        "cwd": cwd_rel,
        "package_json_present": package_json.is_file(),
        "node_modules_present": node_modules.is_dir(),
        "remove_node_modules": node_modules.is_dir(),
        "remove_lock": remove_lock,
        "locks_present": locks_present,
        "skip_install": skip_install,
        "package_manager": pm_label,
        "install_argv": install_argv,
        "timeout_sec": timeout_sec,
    }

    if dry_run:
        return {"ok": True, "dry_run": True, **plan}

    if not package_json.is_file() and not skip_install:
        return {
            "ok": False,
            "error": "package.json not found in working_dir (set skip_install=true to only delete)",
            "cwd": cwd_rel,
        }

    steps: list[dict[str, Any]] = []
    started_all = time.perf_counter()

    if node_modules.is_dir():
        step_started = time.perf_counter()
        try:
            _rmtree_robust(node_modules)
            steps.append(
                {
                    "step": "remove_node_modules",
                    "ok": True,
                    "elapsed_ms": int((time.perf_counter() - step_started) * 1000),
                }
            )
        except Exception as exc:
            return {
                "ok": False,
                "error": f"failed to remove node_modules: {exc}",
                "cwd": cwd_rel,
                "steps": steps,
                "node_modules_present": node_modules.is_dir(),
            }
    else:
        steps.append({"step": "remove_node_modules", "ok": True, "skipped": True})

    if remove_lock:
        removed_locks: list[str] = []
        for name in locks_present:
            lock_path = cwd / name
            try:
                lock_path.unlink()
                removed_locks.append(name)
            except OSError as exc:
                return {
                    "ok": False,
                    "error": f"failed to remove {name}: {exc}",
                    "cwd": cwd_rel,
                    "steps": steps,
                }
        steps.append({"step": "remove_lock", "ok": True, "removed": removed_locks})

    install_out: dict[str, Any] | None = None
    if not skip_install:
        step_started = time.perf_counter()
        try:
            completed = subprocess.run(
                install_argv,
                cwd=str(cwd),
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout_sec,
                check=False,
            )
        except subprocess.TimeoutExpired:
            return {
                "ok": False,
                "error": f"install timed out after {timeout_sec}s",
                "cwd": cwd_rel,
                "steps": steps,
                "package_manager": pm_label,
                "timeout_sec": timeout_sec,
            }
        except OSError as exc:
            return {
                "ok": False,
                "error": f"install spawn failed: {exc}",
                "cwd": cwd_rel,
                "steps": steps,
                "package_manager": pm_label,
            }

        stdout, st_trunc = _truncate(completed.stdout or "")
        stderr, se_trunc = _truncate(completed.stderr or "")
        exit_code = int(completed.returncode)
        install_out = {
            "exit_code": exit_code,
            "stdout": stdout,
            "stderr": stderr,
            "elapsed_ms": int((time.perf_counter() - step_started) * 1000),
            "truncated": bool(st_trunc or se_trunc),
        }
        steps.append({"step": "install", "ok": exit_code == 0, **install_out})
        if exit_code != 0:
            return {
                "ok": False,
                "error": f"install exit_code={exit_code}",
                "cwd": cwd_rel,
                "package_manager": pm_label,
                "steps": steps,
                "node_modules_present": node_modules.is_dir(),
                "install": install_out,
            }

    # After install we expect node_modules present; after delete-only we expect absent.
    ok = (not node_modules.is_dir()) if skip_install else node_modules.is_dir()
    result: dict[str, Any] = {
        "ok": ok,
        "cwd": cwd_rel,
        "package_manager": pm_label,
        "package_manager_bin": pm_bin,
        "remove_lock": remove_lock,
        "skip_install": skip_install,
        "node_modules_present": node_modules.is_dir(),
        "clean": not node_modules.is_dir() if skip_install else bool(node_modules.is_dir()),
        "steps": steps,
        "elapsed_ms": int((time.perf_counter() - started_all) * 1000),
        "timeout_sec": timeout_sec,
    }
    if install_out is not None:
        result["install"] = install_out
    if not ok:
        result["error"] = (
            "node_modules still present after delete"
            if skip_install
            else "node_modules missing after install"
        )
    return result


def main() -> None:
    core = _agent_root() / "agent-core"
    if str(core) not in sys.path:
        sys.path.insert(0, str(core))
    from evolve_tool_io import run_tool_main

    run_tool_main(run_repair)


if __name__ == "__main__":
    main()
