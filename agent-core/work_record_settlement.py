"""Persist a bounded host-run receipt for a run already matched by the server.

This records only local lifecycle facts, never requirement completion or verification.
It is not a general execution audit log or proof of side effects, tests, or user goals.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import re
import threading
import uuid
from collections.abc import Sequence
from typing import Any, Literal

from evolution.context import normalize_host_run_id
from session import Session


@dataclass(frozen=True)
class BoundExecution:
    """Identity captured from an already-authorized, single execution context."""

    session_id: str
    item_id: str
    requirement_id: str
    run_id: str
    # Present only for an ordinary explicit work-record capture; never inferred
    # from a project-worker batch or generated by the requirement text.
    capture_request_id: str | None = None
    reservation_id: str | None = None
    parent_run_id: str | None = None


@dataclass(frozen=True)
class ExecutionReceipt:
    """Structured server-created lifecycle receipt; never carry model/tool text.

    ``finish_reason`` is optional for backward compatibility and is a restricted
    upstream lifecycle label, not an independently authenticated claim.
    """

    session_id: str
    item_id: str
    requirement_id: str
    run_id: str
    sequence: int
    outcome: Literal["succeeded", "failed", "cancelled", "timeout", "exception"]
    finish_reason: Literal["completed", "stop", "cancelled", "timeout", "error", "paused", "unknown"] | None = None
    host_tool_receipts: Sequence[dict[str, Any]] = ()
    omitted_count: int = 0
    # Worker read evidence remains a distinct receipt type, never a host tool call.
    project_worker_read_attempts: dict[str, Any] | None = None
    project_worker_write_receipts: list[dict[str, Any]] | None = None


@dataclass(frozen=True)
class VerificationReceipt:
    """Independent, reviewable verification evidence for the same bound run."""

    session_id: str
    item_id: str
    requirement_id: str
    run_id: str
    status: Literal["passed", "failed", "not_run"]
    evidence_refs: tuple[str, ...] = ()


@dataclass(frozen=True)
class SettlementResult:
    status: Literal["recorded", "rejected", "executed_not_recorded", "conflict", "unsupported"]
    result_id: str | None = None
    record_status: str | None = None
    retry_execution: bool = False
    reason: str = ""
    publication_status: Literal[
        "intent_recorded", "replay_no_new_intent", "result_saved_without_intent",
    ] | None = None


@dataclass(frozen=True)
class AssistantExcerptAppendResult:
    """Result of appending a confirmed assistant excerpt, separate from run settlement."""

    status: Literal["recorded", "rejected", "conflict"]
    excerpt_id: str | None = None
    reason: str = ""


_HOST_TOOL_NAME_RE = re.compile(r"[a-z][a-z0-9_]{0,63}\Z")
_HOST_TOOL_RECEIPT_KEYS = frozenset({"host_run_id", "call_id", "tool", "ok"})
_MAX_HOST_TOOL_RECEIPTS = 20


class WorkRecordSettlementAdapter:
    """Serialize one bound run and persist sanitized, server-provided host facts.

    The caller supplies the server-matched binding and receipt; this adapter does not
    independently authenticate who constructed them. Verification data is ignored.
    Persistence uses durable current-run CAS, records requirement status ``unknown``
    and verification ``not_verified``, and never starts or reruns execution. It records
    only sequence, an optional allowlisted finish-reason label, and bounded structured
    host tool-call facts, never tool arguments/output or ``outcome``.
    """

    def __init__(self, store: Any, binding: BoundExecution) -> None:
        if not self._valid_identity(binding):
            raise ValueError("trusted binding identity is incomplete")
        self._store = store
        self._binding = binding
        self._lock = threading.RLock()

    @staticmethod
    def _valid_identity(value: Any) -> bool:
        return all(isinstance(getattr(value, name, None), str) and getattr(value, name).strip()
                   for name in ("session_id", "item_id", "requirement_id", "run_id"))

    def _matches(self, value: Any) -> bool:
        return self._valid_identity(value) and all(
            getattr(value, key) == getattr(self._binding, key)
            for key in ("session_id", "item_id", "requirement_id", "run_id")
        )

    @staticmethod
    def _result_id(binding: BoundExecution) -> str:
        raw = "\0".join((binding.session_id, binding.item_id, binding.requirement_id, binding.run_id))
        return "settlement-" + hashlib.sha256(raw.encode("utf-8")).hexdigest()

    def _sanitize_host_tool_receipts(self, execution: ExecutionReceipt) -> tuple[list[dict[str, Any]], int] | None:
        receipts = execution.host_tool_receipts
        omitted_count = execution.omitted_count
        if not isinstance(receipts, (tuple, list)) or len(receipts) > _MAX_HOST_TOOL_RECEIPTS:
            return None
        if type(omitted_count) is not int or omitted_count < 0:
            return None

        expected_host_run_id = normalize_host_run_id(self._binding.run_id) if receipts or omitted_count else ""
        if (receipts or omitted_count) and not expected_host_run_id:
            return None

        sanitized: list[dict[str, Any]] = []
        seen_call_ids: set[str] = set()
        for entry in receipts:
            if type(entry) is not dict or set(entry) != _HOST_TOOL_RECEIPT_KEYS:
                return None
            host_run_id = entry.get("host_run_id")
            call_id = entry.get("call_id")
            tool = entry.get("tool")
            ok = entry.get("ok")
            normalized_host_run_id = normalize_host_run_id(host_run_id) if type(host_run_id) is str else ""
            if not normalized_host_run_id or normalized_host_run_id != expected_host_run_id:
                return None
            if type(call_id) is not str or len(call_id) != 36:
                return None
            try:
                parsed_call_id = uuid.UUID(call_id)
            except (ValueError, AttributeError):
                return None
            canonical_call_id = str(parsed_call_id)
            if canonical_call_id != call_id.lower() or canonical_call_id in seen_call_ids:
                return None
            if type(tool) is not str or _HOST_TOOL_NAME_RE.fullmatch(tool) is None:
                return None
            if type(ok) is not bool:
                return None
            seen_call_ids.add(canonical_call_id)
            # Copy only the four permitted scalar fields; caller-owned dictionaries
            # and any unsupported nested data never reach durable storage.
            sanitized.append({
                "host_run_id": normalized_host_run_id,
                "call_id": canonical_call_id,
                "tool": tool,
                "ok": ok,
            })
        return sanitized, omitted_count

    def _has_explicit_independent_capture(self, session: Session) -> bool:
        request_id = self._binding.capture_request_id
        if type(request_id) is not str:
            return False
        try:
            parsed = uuid.UUID(request_id)
            canonical = str(parsed)
        except (ValueError, AttributeError, TypeError):
            return False
        if canonical != request_id:
            return False
        try:
            item = self._store.get_item(self._binding.item_id)
            if (type(item) is not dict or item.get("item_id") != self._binding.item_id
                    or item.get("scope") != {"kind": "independent", "object_ref": None}):
                return False
            history = item.get("history")
            batch_keys = [event.get("idempotency_key") for event in history
                          if type(event) is dict and type(event.get("idempotency_key")) is str] if type(history) is list else []
            if (item.get("title") == "多项目任务批次"
                    and any(key.startswith("worker-batch-original:") for key in batch_keys)
                    and any(key.startswith("worker-batch-task:") for key in batch_keys)):
                return False
            requirements = item.get("requirements")
            matches = [row for row in requirements if type(row) is dict
                       and row.get("requirement_id") == self._binding.requirement_id]
            if len(matches) != 1 or matches[0].get("current_run_id") != self._binding.run_id:
                return False
            edges = [event for event in item.get("history", [])
                     if type(event) is dict and event.get("event_id") == canonical
                     and event.get("kind") == "requirement_added"
                     and type(event.get("payload")) is dict
                     and event["payload"].get("requirement_id") == self._binding.requirement_id
                     and type(event.get("idempotency_key")) is str
                     and event["idempotency_key"].startswith(f"desktop:user.message:{canonical}:")]
            return len(edges) == 1 and getattr(self._store, "_session", None) is session
        except Exception:
            return False

    def append_assistant_reply_excerpt(
        self, execution: ExecutionReceipt | None, *, assistant_excerpt: str,
        source_availability: Literal["available", "unavailable"],
        sources: Sequence[dict[str, Any]] = (),
        confirm_fn: Any,
    ) -> AssistantExcerptAppendResult:
        """Append one explicitly approved excerpt to this exact settled run.

        The trusted host supplies the excerpt from the bound assistant reply.
        The Store CAS proves the run is still current and unknown/not_verified;
        this does not change settlement, verification, or card-publication state.
        """
        rejected = AssistantExcerptAppendResult
        if not isinstance(execution, ExecutionReceipt) or not self._matches(execution):
            return rejected("rejected", reason="missing_or_mismatched_execution_receipt")
        session = getattr(self._store, "_session", None)
        if not isinstance(session, Session) or session.conversation_id != self._binding.session_id:
            return rejected("rejected", reason="store_session_mismatch")
        if (type(execution.sequence) is not int or execution.sequence < 1
                or type(execution.outcome) is not str or execution.outcome not in {
                    "succeeded", "failed", "cancelled", "timeout", "exception",
                }
                or (execution.finish_reason is not None and (
                    type(execution.finish_reason) is not str or execution.finish_reason not in {
                        "completed", "stop", "cancelled", "timeout", "error", "paused", "unknown",
                    }
                ))):
            return rejected("rejected", reason="invalid_execution_receipt")
        if (type(assistant_excerpt) is not str or not assistant_excerpt.strip()
                or type(source_availability) is not str
                or source_availability not in {"available", "unavailable"}
                or not isinstance(sources, (tuple, list)) or len(sources) > 16
                or not callable(confirm_fn)):
            return rejected("rejected", reason="invalid_assistant_excerpt")
        try:
            if len(assistant_excerpt.encode("utf-8")) > 4096:
                return rejected("rejected", reason="assistant_excerpt_limit_exceeded")
            safe_sources = [dict(source) if type(source) is dict else source for source in sources]
            self._store._validate_source_refs(safe_sources)
        except (UnicodeError, TypeError, ValueError):
            return rejected("rejected", reason="invalid_assistant_excerpt_sources")
        if ((source_availability == "available" and not safe_sources)
                or (source_availability == "unavailable" and safe_sources)):
            return rejected("rejected", reason="source_availability_mismatch")

        # Avoid prompting for a binding already known stale. Store repeats these
        # checks under its cross-process write lock after the user confirms.
        try:
            bound_run_id = normalize_host_run_id(self._binding.run_id)
            item = self._store.get_item(self._binding.item_id)
            requirements = item.get("requirements") if type(item) is dict else None
            runs = item.get("runs") if type(item) is dict else None
            matching_requirements = [row for row in requirements if type(row) is dict
                                     and row.get("requirement_id") == self._binding.requirement_id] if type(requirements) is list else []
            matching_runs = [row for row in runs if type(row) is dict
                             and normalize_host_run_id(row.get("run_id")) == bound_run_id
                             and row.get("requirement_id") == self._binding.requirement_id] if type(runs) is list else []
            run = matching_runs[0] if len(matching_runs) == 1 else None
            verification = run.get("verification") if type(run) is dict else None
            host = verification.get("host_execution") if type(verification) is dict else None
            if (len(matching_requirements) != 1
                    or normalize_host_run_id(matching_requirements[0].get("current_run_id")) != bound_run_id
                    or type(run) is not dict or run.get("status") != "unknown"
                    or type(verification) is not dict or verification.get("status") != "not_verified"
                    or type(host) is not dict or host.get("sequence") != execution.sequence
                    or host.get("finish_reason") != execution.finish_reason):
                return rejected("rejected", reason="stale_run")
        except Exception:
            return rejected("rejected", reason="bound_run_unavailable")

        preview_payload = {
            "purpose": "assistant_reply_excerpt",
            "session_id": self._binding.session_id,
            "item_id": self._binding.item_id,
            "requirement_id": self._binding.requirement_id,
            "run_id": self._binding.run_id,
            "assistant_reply_excerpt": assistant_excerpt,
            "source_availability": source_availability,
            "sources": safe_sources,
            "result_status": "unknown",
            "verification_status": "not_verified",
        }
        try:
            preview = (
                "工作记录助理回复摘录本地保存确认\n"
                "以下 JSON 即为拟追加字段；摘录仅作该回合的未核对记录，不代表要求成功或验证通过。\n"
                + json.dumps(preview_payload, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False)
            )
            choice, confirmation_id = confirm_fn(preview)
            canonical_confirmation = str(uuid.UUID(confirmation_id)) if type(confirmation_id) is str else ""
        except (TypeError, ValueError, AttributeError, UnicodeError):
            return rejected("rejected", reason="assistant_excerpt_confirmation_failed")
        if (not canonical_confirmation
                or not isinstance(choice, str)
                or choice.strip().casefold() not in {"y", "yes", "confirm", "allow"}):
            return rejected("rejected", reason="assistant_excerpt_storage_not_authorized")

        try:
            entry, committed = self._store.append_assistant_reply_excerpt_if_current_run(
                self._binding.item_id, self._binding.requirement_id,
                run_id=self._binding.run_id, sequence=execution.sequence,
                finish_reason=execution.finish_reason, text=assistant_excerpt,
                source_availability=source_availability, sources=safe_sources,
            )
        except Exception as exc:
            from work_records import WorkRecordConflict, WorkRecordStaleRun
            if isinstance(exc, WorkRecordStaleRun):
                return rejected("rejected", reason="stale_run")
            if isinstance(exc, WorkRecordConflict):
                return AssistantExcerptAppendResult("conflict", reason="assistant_excerpt_conflict")
            return rejected("rejected", reason="assistant_excerpt_storage_failed")
        return AssistantExcerptAppendResult(
            "recorded", excerpt_id=entry["excerpt_id"],
            reason="idempotent_replay" if not committed else "",
        )

    def settle(self, execution: ExecutionReceipt | None,
               verification: VerificationReceipt | None = None, *,
               publish_project_update: bool = False,
               publish_independent_update: bool = False,
               publication_window_seconds: float = 30.0) -> SettlementResult:
        with self._lock:
            if not isinstance(execution, ExecutionReceipt) or not self._matches(execution):
                return SettlementResult("rejected", record_status="unknown", reason="missing_or_mismatched_execution_receipt")
            session = getattr(self._store, "_session", None)
            if not isinstance(session, Session) or session.conversation_id != self._binding.session_id:
                return SettlementResult("rejected", record_status="unknown", reason="store_session_mismatch")
            if type(execution.sequence) is not int or execution.sequence < 1:
                return SettlementResult("rejected", record_status="unknown", reason="invalid_execution_sequence")
            if not isinstance(execution.outcome, str) or execution.outcome not in {
                "succeeded", "failed", "cancelled", "timeout", "exception",
            }:
                return SettlementResult("rejected", record_status="unknown", reason="invalid_execution_outcome")
            if execution.finish_reason is not None and (
                type(execution.finish_reason) is not str
                or execution.finish_reason not in {
                    "completed", "stop", "cancelled", "timeout", "error", "paused", "unknown",
                }
            ):
                return SettlementResult("rejected", record_status="unknown", reason="invalid_execution_finish_reason")
            sanitized_host_tools = self._sanitize_host_tool_receipts(execution)
            if sanitized_host_tools is None:
                return SettlementResult("rejected", record_status="unknown", reason="invalid_host_tool_receipts")
            project_worker_reads = execution.project_worker_read_attempts
            if project_worker_reads is not None:
                from project_worker_read_evidence import validate_project_worker_read_attempts
                if (type(project_worker_reads) is not dict
                        or set(project_worker_reads) != {"available", "attempts"}
                        or not validate_project_worker_read_attempts(
                            project_worker_reads.get("available"), project_worker_reads.get("attempts"),
                        )):
                    return SettlementResult("rejected", record_status="unknown",
                                            reason="invalid_project_worker_read_attempts")
                project_worker_reads = {
                    "available": project_worker_reads["available"],
                    "attempts": [dict(row) for row in project_worker_reads["attempts"]],
                }
            project_worker_writes = execution.project_worker_write_receipts
            if project_worker_writes is not None:
                if (type(project_worker_writes) is not list or len(project_worker_writes) > 64):
                    return SettlementResult("rejected", record_status="unknown",
                                            reason="invalid_project_worker_write_receipts")
                safe_writes: list[dict[str, Any]] = []
                seen_paths: set[str] = set()
                statuses = {"written", "verification_failed", "not_written", "outcome_unknown", "applied_unledgered"}
                verifications = {"content_match", "content_mismatch", "not_verified", "readback_failed", "readback_after_error"}
                for row in project_worker_writes:
                    if (type(row) is not dict or set(row) != {
                            "path", "status", "verification", "characters_read_back", "readback_succeeded", "error_code"}):
                        return SettlementResult("rejected", record_status="unknown",
                                                reason="invalid_project_worker_write_receipts")
                    path, status, write_verification = row["path"], row["status"], row["verification"]
                    chars, readback, error = row["characters_read_back"], row["readback_succeeded"], row["error_code"]
                    if (type(path) is not str or not path or len(path.encode("utf-8")) > 1024
                            or path.startswith("/") or "\\" in path or ":" in path
                            or any(part in ("", ".", "..") for part in path.split("/"))
                            or path in seen_paths or type(status) is not str or status not in statuses
                            or type(write_verification) is not str or write_verification not in verifications
                            or type(chars) is not int or chars < 0 or type(readback) is not bool
                            or type(error) is not str or len(error) > 128
                            or any(ord(c) < 32 for c in error)):
                        return SettlementResult("rejected", record_status="unknown",
                                                reason="invalid_project_worker_write_receipts")
                    seen_paths.add(path)
                    safe_writes.append(dict(row))
                project_worker_writes = safe_writes
            if verification is not None and (
                not isinstance(verification, VerificationReceipt) or not self._matches(verification)
            ):
                return SettlementResult("rejected", record_status="unknown", reason="mismatched_verification_receipt")

            if (type(publish_project_update) is not bool or type(publish_independent_update) is not bool
                    or (publish_project_update and publish_independent_update)):
                return SettlementResult("rejected", record_status="unknown", reason="invalid_publication_intent_flag")
            if publish_independent_update and not self._has_explicit_independent_capture(session):
                return SettlementResult("rejected", record_status="unknown", reason="independent_capture_binding_missing")
            verified_write_count = sum(
                row["status"] == "written" and row["verification"] == "content_match"
                and row["readback_succeeded"] for row in (project_worker_writes or [])
            )
            summary = "Structured host execution receipt recorded; requirement outcome remains unknown."
            if project_worker_writes is not None:
                summary = (
                    f"Worker write receipts: {verified_write_count} target(s) were read back and matched; "
                    "overall requirement outcome remains unverified."
                )
            result_id = self._result_id(self._binding)
            cas_name = ("record_server_settlement_if_current_run" if publish_project_update
                        else "record_independent_server_settlement_if_current_run" if publish_independent_update
                        else "record_result_if_current_run")
            cas = getattr(self._store, cas_name, None)
            if not callable(cas):
                return SettlementResult("unsupported", result_id, "unknown", False,
                                        "store_lacks_atomic_current_run_cas")
            commit_feedback = {} if publish_project_update or publish_independent_update else None
            try:
                cas(
                    self._binding.item_id,
                    self._binding.requirement_id,
                    run_id=self._binding.run_id,
                    result_id=result_id,
                    status="unknown",
                    summary=summary,
                    verification={
                        "status": "not_verified",
                        "evidence_refs": [],
                        "host_execution": {
                            "sequence": execution.sequence,
                            **({} if self._binding.reservation_id is None else {
                                "reservation_id": self._binding.reservation_id,
                                "parent_run_id": self._binding.parent_run_id,
                            }),
                            **({} if execution.finish_reason is None else {
                                "finish_reason": execution.finish_reason,
                            }),
                            **({} if not sanitized_host_tools[0] and sanitized_host_tools[1] == 0 else {
                                "host_tool_receipts": sanitized_host_tools[0],
                                "omitted_count": sanitized_host_tools[1],
                            }),
                            **({} if project_worker_reads is None else {
                                "project_worker_read_attempts": project_worker_reads,
                            }),
                            **({} if project_worker_writes is None else {
                                "project_worker_write_receipts": project_worker_writes,
                            }),
                        },
                    },
                    sources=[],
                    **({"publication_window_seconds": publication_window_seconds,
                        "_commit_feedback": commit_feedback}
                       if publish_project_update or publish_independent_update else {}),
                )
            except Exception as exc:
                # Import lazily so the injected protocol remains independently loadable.
                from work_records import WorkRecordConflict, WorkRecordStaleRun
                if isinstance(exc, WorkRecordStaleRun):
                    return SettlementResult("rejected", result_id, "unknown", False, "stale_run")
                if isinstance(exc, WorkRecordConflict):
                    return SettlementResult("conflict", result_id, "unknown", False, "result_id_fact_conflict")
                return SettlementResult("executed_not_recorded", result_id, "unknown", False,
                                        "storage_failed_no_execution_replay")
            publication_status = None
            if commit_feedback is not None:
                if commit_feedback.get("intent_changed") is True:
                    publication_status = "intent_recorded"
                elif commit_feedback.get("result_changed") is False:
                    publication_status = "replay_no_new_intent"
                else:
                    publication_status = "result_saved_without_intent"
            return SettlementResult(
                "recorded", result_id, "unknown", publication_status=publication_status,
            )
